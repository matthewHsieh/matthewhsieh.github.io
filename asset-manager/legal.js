// 一行版：放在登入頁與總覽頁尾，永遠看得到
export const DISCLAIMER_ONE_LINE =
  '本工具僅供個人記帳與研究，不是投資建議；數字可能延遲或錯誤，下單前請自行向券商與官方來源查證。';

// localStorage 的鍵。換版本號可以讓所有人重看一次（條文有實質變動時才換）
const ACK_KEY = 'disclaimerAck';
const ACK_VERSION = '2026-09-12';

export function disclaimerAcked() {
  try {
    return localStorage.getItem(ACK_KEY) === ACK_VERSION;
  } catch {
    return false;   // 無痕模式讀不到就當作沒看過，寧可多顯示一次
  }
}

export function ackDisclaimer() {
  try {
    localStorage.setItem(ACK_KEY, ACK_VERSION);
  } catch {
    /* 存不起來就算了，下次再顯示一次，不影響功能 */
  }
}

