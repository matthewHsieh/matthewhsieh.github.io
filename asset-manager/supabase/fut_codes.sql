-- ============================================================
-- 股票期貨契約代號對照（人工維護）
--
-- 期交所的股票期貨用兩碼英文代號，加上 F 就是行情檔裡的契約代號：
--   台玻 1802 → KU → KUF
-- 這個對照表在期交所網頁上，不是 OpenAPI，所以用爬的再生成這個檔。
-- 重新產生方式：抓 https://www.taifex.com.tw/cht/2/stockLists 解析表格
-- （契約代號 / 標的證券全名 / 證券代號 / 簡稱）。新標的掛牌時才需要重跑。
-- ============================================================

create table if not exists public.fut_codes (
  symbol text primary key,
  code   text not null,      -- 兩碼，行情檔裡要加 F
  name   text
);
alter table public.fut_codes enable row level security;
drop policy if exists "read fut codes" on public.fut_codes;
create policy "read fut codes" on public.fut_codes for select to authenticated using (true);

