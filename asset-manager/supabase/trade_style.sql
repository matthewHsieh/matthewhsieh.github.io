-- ============================================================
-- 交易分類：當沖 / 隔日衝 / 波段
--
--   原本只有 is_day_trade 一個布林值，分得出當沖與非當沖，
--   但「隔日衝」跟「抱兩個月的波段」混在同一格裡看不出差別。
--
--   **不能把隔日衝也記成 is_day_trade。** 那個旗標不只是分類，
--   它還決定兩件事：
--     1. 證交稅率——現股當沖減半（0.15%），隔日衝沒有這個優惠（0.30%）。
--     2. 損益怎麼算——當沖是同一組買賣直接 FIFO 配對，不碰長期部位；
--        隔日衝跟波段一樣，要用平均成本結算。
--   借用它會讓稅少算一半，那是真的錢。
--
--   所以另外加一個純粹的標籤欄位 style：
--     null / 'swing'   波段（沿用既有資料，不用回填）
--     'overnight'      隔日衝
--     'day'            當沖（跟 is_day_trade 並存，之後若要統一才用得到）
--   既有的列一律不動——style 是 null 的就看 is_day_trade，行為完全不變。
-- ============================================================

alter table public.trades add column if not exists style text;

comment on column public.trades.style is
  '交易風格標籤：overnight=隔日衝，day=當沖，null/swing=波段。'
  '**只用於分類統計**，稅率與損益計算仍看 is_day_trade。';
