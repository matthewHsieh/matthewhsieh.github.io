-- ============================================================
-- 買 call 解 ban 需要的欄位：記下當時的指數
--
--   判斷「深度價內」要拿履約價跟遠期指數比，但**遠期指數只有收盤值**。
--   期交所的每日行情檔要隔一天才進得來，而他通常是收盤後才回來補紀錄，
--   所以判斷的時候手上永遠是昨天的數字。
--   台股日波動大約就是 1%，跟「價內 1% 以上」這個門檻同一個量級——
--   換句話說，只靠昨天的收盤去判斷，**在門檻附近等於擲硬幣**。
--   2026-09-16 那筆 45500 買權就是例子：當下真的價內 700 多點，
--   用 9/15 的遠期 45,730 去算只剩 230 點，會被判成違規。
--
--   所以讓他在表單上填「當時的指數」，預設帶最新一筆遠期價。
--   純新增欄位，既有的列一律是 null，照舊走「用最新遠期價」的路。
--
--   **存下來還有一個好處**：心得頁的每日檢討是重新算一次違規，
--   不是讀當初的判斷。沒存的話，記錄當下說沒問題、隔天回頭看變成違規，
--   守規天數會自己斷掉，而使用者完全不知道為什麼。
-- ============================================================

alter table public.trades add column if not exists opt_fwd numeric;

comment on column public.trades.opt_fwd is
  '記這筆選擇權交易時的指數（遠期或現貨皆可），用來判斷價內程度。'
  'null 代表沒填，改用 market_prices 裡最新的 FWD| 報價。';
