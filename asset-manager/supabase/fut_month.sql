-- ============================================================
-- 期貨部位記月份
--
--   原本 futures.contract 存的只是顯示名稱（「4938 和碩 大型個股期」），
--   **完全沒有月份**。手上五口部位裡金居與台玻是十月倉、其餘是九月倉，
--   但畫面上長得一模一樣，看不出差別，轉倉之後也沒有任何地方會變。
--
--   加一個 month 欄位（'YYYYMM'）。純新增，不動任何既有欄位。
--
--   為什麼值得記：**最後交易日是交割月份的第三個星期三**
--   （臺灣期交所股票期貨契約規格，最後結算日與最後交易日同一天）。
--   知道月份才算得出剩幾天，也才知道哪一口快要被結算掉。
--   掛牌月份是「交易當月起連續 2 個月，再加上 3、6、9、12 月中
--   3 個接續季月」，共 5 個。
-- ============================================================

alter table public.futures add column if not exists month text;

comment on column public.futures.month is
  '交割月份 YYYYMM。最後交易日為該月第三個星期三（遇假日順延）。';

-- 索引不需要：一個人的期貨部位就那幾列。
